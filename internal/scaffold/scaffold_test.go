func TestGuardVocabWarnsOnDeliveredArtifacts(t *testing.T) {
	if !hasJQ(t) {
		t.Skip("jq ausente; o hook faz no-op por design")
	}

	cases := []struct {
		name    string
		relPath string
		content string
		warns   bool
	}{
		{"readme cita spec numerada", "README.md", "Ver spec 012 para detalhes.\n", true},
		{"codigo cita CA", "internal/foo/foo.go", "// implementa CA-03\n", true},
		{"codigo cita RF", "internal/foo/foo.go", "// conforme RF-07\n", true},
		{"readme cita criterio de aceite", "README.md", "Cada critério de aceite vira teste.\n", true},
		{"teste pode citar CA", "internal/foo/foo_test.go", "// CA-01: rejeita vazio\n", false},
		{"CLAUDE.md pode citar spec", "CLAUDE.md", "Ao receber uma spec 012, siga.\n", false},
		{"claude dir pode citar", ".claude/commands/x.md", "Leia a spec 012.\n", false},
		{"OpenAPI spec passa limpo", "README.md", "Servimos uma OpenAPI spec em /docs.\n", false},
		{"spec-driven passa limpo", "README.md", "Fluxo spec-driven development.\n", false},
		// A isenção de teste vale por segmento inteiro, não por substring:
		// "latest" e "attestation" contêm "test" e são artefato entregue.
		{"latest nao e diretorio de teste", "docs/latest/README.md", "Ver spec 012.\n", true},
		{"attestation nao e diretorio de teste", "attestation/README.md", "Ver spec 012.\n", true},
		{"diretorio test de verdade e isento", "test/helper.md", "Ver spec 012.\n", false},
		{"diretorio tests de verdade e isento", "pkg/tests/helper.md", "Ver spec 012.\n", false},
		// .superpowers/ é diretório de sessão local, não artefato entregue.
		// Acusá-lo faz o hook gritar justamente onde a nota de processo mora,
		// e ruído é o que faz um hook de aviso deixar de ser lido.
		{"superpowers e sessao local", ".superpowers/sdd/progress.md", "Task 1 fecha o CA-01 da spec 012.\n", false},
		{"superpowers aninhado", "sub/.superpowers/x.md", "Ver spec 012.\n", false},
		// Simétrico aos casos de "latest"/"attestation" acima: a isenção vale
		// pelo segmento `.superpowers` inteiro, com o ponto. Sem estes dois, um
		// padrão frouxo (`*superpowers*`) passa na suíte e cala o hook justamente
		// em docs/superpowers/, que é artefato entregue — não sessão local.
		{"docs superpowers e artefato entregue", "docs/superpowers/plans/x.md", "Ver spec 012.\n", true},
		{"superpowers sem ponto nao e isento", "superpowers/x.md", "Ver spec 012.\n", true},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()

			if _, err := WriteFiles([]profile.ScaffoldFile{{Path: ".claude/hooks/guard-vocab.sh"}}, Options{
				Target: dir,
				Data:   Data{ProjectName: "demo", Stack: "go"},
			}); err != nil {
				t.Fatal(err)
			}

			target := filepath.Join(dir, filepath.FromSlash(tc.relPath))
			if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(target, []byte(tc.content), 0o644); err != nil {
				t.Fatal(err)
			}

			payloadPath := filepath.Join(dir, "payload.json")
			payload := `{"tool_input":{"file_path":` + strconv.Quote(target) + `}}`
			if err := os.WriteFile(payloadPath, []byte(payload), 0o644); err != nil {
				t.Fatal(err)
			}

			res, err := runner.ExecRunner{}.Run(context.Background(), runner.Command{
				Name: "bash",
				Args: []string{"-c", "cat " + payloadPath + " | bash " + filepath.Join(dir, ".claude/hooks/guard-vocab.sh")},
				Dir:  dir,
			})
			if err != nil {
				t.Fatalf("rodando guard-vocab.sh: %v", err)
			}

			warned := res.ExitCode == 2
			if warned != tc.warns {
				t.Errorf("avisou = %v, want %v (exit %d, stderr %q)", warned, tc.warns, res.ExitCode, res.Stderr)
			}
			if warned && !strings.Contains(res.Stderr, tc.relPath) {
				t.Errorf("stderr does not name the file: %q", res.Stderr)
			}
		})
	}
}

