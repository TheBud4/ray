func TestEnsureTemplatesOverlayWinsOverEmbed(t *testing.T) {
	overlayDir := t.TempDir()
	if err := EnsureTemplates(overlayDir); err != nil {
		t.Fatalf("EnsureTemplates() error = %v", err)
	}

	overlayFile := filepath.Join(overlayDir, "CLAUDE.md.tmpl")
	if _, err := os.Stat(overlayFile); err != nil {
		t.Fatalf("stat overlay CLAUDE.md.tmpl: %v", err)
	}
	custom := []byte("# {{.ProjectName}} (overlay custom)")
	if err := os.WriteFile(overlayFile, custom, 0o644); err != nil {
		t.Fatal(err)
	}

	target := t.TempDir()
	_, err := WriteFiles([]profile.ScaffoldFile{{Path: "CLAUDE.md"}}, Options{
		Target:       target,
		Data:         Data{ProjectName: "demo"},
		TemplatesDir: overlayDir,
	})
	if err != nil {
		t.Fatal(err)
	}

	got, err := os.ReadFile(filepath.Join(target, "CLAUDE.md"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(got), "overlay custom") {
		t.Fatalf("CLAUDE.md = %q, want overlay content to win", got)
	}
}

func TestEnsureTemplatesNeverOverwrites(t *testing.T) {
	overlayDir := t.TempDir()
	overlayFile := filepath.Join(overlayDir, "CLAUDE.md.tmpl")
	if err := os.MkdirAll(overlayDir, 0o755); err != nil {
		t.Fatal(err)
	}
	custom := []byte("pré-existente")
	if err := os.WriteFile(overlayFile, custom, 0o644); err != nil {
		t.Fatal(err)
	}

	if err := EnsureTemplates(overlayDir); err != nil {
		t.Fatalf("EnsureTemplates() error = %v", err)
	}

	got, err := os.ReadFile(overlayFile)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != string(custom) {
		t.Fatalf("EnsureTemplates overwrote a pre-existing overlay file: got %q, want %q", got, custom)
	}
}
